"""
splice_v3_contrast_table.py — replaces the appendix longtable tab:app_contrasts in
output/main7_humanized.tex by the table generated by review_v3_contrast_table.py
(docs/results_v3_mrp/analysis/REVIEW_v3_contrast_table.tex).  The block replaced runs from the line
'{\\scriptsize\\setlength{\\tabcolsep}{4pt}' that precedes '\\begin{longtable}' to the line '}' that
follows '\\end{longtable}'.  Exactly one such block must exist.

Usage: python splice_v3_contrast_table.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TEX = os.path.abspath(os.path.join(HERE, "..", "..", "output", "main7_humanized.tex"))
NEW = os.path.join(HERE, "..", "docs", "results_v3_mrp", "analysis", "REVIEW_v3_contrast_table.tex")

with open(TEX, encoding="utf-8") as f:
    lines = f.read().split("\n")
with open(NEW, encoding="utf-8") as f:
    new = f.read().rstrip("\n").split("\n")

starts = [i for i, l in enumerate(lines) if l.strip() == "\\begin{longtable}{llrrrrrr}"]
assert len(starts) == 1, starts
s = starts[0] - 1
assert lines[s].strip() == "{\\scriptsize\\setlength{\\tabcolsep}{4pt}", lines[s]
e = next(i for i in range(s, len(lines)) if lines[i].strip() == "\\end{longtable}") + 1
assert lines[e].strip() == "}", lines[e]
assert "tab:app_contrasts" in "\n".join(lines[s:e])
assert new[0] == lines[s] and new[-1].strip() == "}"
out = lines[:s] + new + lines[e + 1:]
with open(TEX, "w", encoding="utf-8", newline="") as f:
    f.write("\n".join(out))
print(f"replaced lines {s + 1}-{e + 1} ({e - s + 1} lines) by {len(new)} lines")
