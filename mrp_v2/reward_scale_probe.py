"""
reward_scale_probe.py — per-step sign and scale of every reward variant,
computed on IDENTICAL trajectories (so differences are due to the reward only).

Trajectories are generated by (i) a random-logit policy and (ii) a "greedy
deficit" heuristic (allocation proportional to deviation), in each condition.
For every step we evaluate all reward functions on the same (d_t, d_{t+1}).
"""
import os
import sys
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from mrp_env import MRPEnv, make_reward_fn, REWARD_SPECS  # noqa: E402
from runner import CONDITIONS  # noqa: E402

VARS = [v for v in REWARD_SPECS if v != "OR_adapt"]


def run(out_csv, episodes=20):
    fns = {v: make_reward_fn(v) for v in VARS}
    rows = []
    for c, p in CONDITIONS.items():
        for pol in ("random", "greedy"):
            env = MRPEnv(p["n"], p["budget"], p["noise"], fns["DR"])
            rng = np.random.default_rng(0)
            acc = {v: [] for v in VARS}
            for ep in range(episodes):
                env.reset(5000 + ep)
                done = False
                while not done:
                    if pol == "random":
                        logits = rng.normal(0, 1, p["n"])
                    else:
                        logits = 20.0 * np.abs(env._obs_v)
                    _, _, term, trunc, info = env.step(logits)
                    d0, d1 = info["dev_prev"], info["dev"]
                    for v in VARS:
                        acc[v].append(fns[v](d0, d1))
                    done = term or trunc
            for v in VARS:
                x = np.array(acc[v])
                rows.append(dict(cond=c, policy=pol, variant=v, mean=x.mean(), std=x.std(),
                                 frac_pos=(x > 0).mean(), frac_neg=(x < 0).mean(),
                                 p05=np.percentile(x, 5), p95=np.percentile(x, 95)))
    df = pd.DataFrame(rows)
    df.to_csv(out_csv, index=False)
    return df


if __name__ == "__main__":
    out = os.path.join(HERE, "..", "docs", "results_v2", "analysis")
    os.makedirs(out, exist_ok=True)
    df = run(os.path.join(out, "reward_scale_probe.csv"))
    piv = df[df.policy == "random"].pivot_table(index="variant", values=["mean", "std", "frac_pos"],
                                                aggfunc="mean")
    print(piv.round(4))
